// Utility to generate initial candle history
const generateChartHistory = (basePrice: number): ChartPoint[] => {
  const points: ChartPoint[] = [];
  let current = basePrice * 0.92;
  const now = new Date();
  for (let i = 30; i >= 0; i--) {
    const d = new Date(now.getTime() - i * 24 * 60 * 60 * 1000);
    const timeStr = `${d.getMonth() + 1}/${d.getDate()}`;
    const delta = (Math.random() - 0.48) * (basePrice * 0.03);
    const open = Number((current).toFixed(2));
    const close = Number((current + delta).toFixed(2));
    const high = Number((Math.max(open, close) + Math.random() * (basePrice * 0.015)).toFixed(2));
    const low = Number((Math.min(open, close) - Math.random() * (basePrice * 0.015)).toFixed(2));
    const volume = Math.floor(Math.random() * 50000) + 10000;

    points.push({
      time: timeStr,
      open,
      high,
      low,
      close,
      volume,
    });
    current = close;
  }
  return points;
};

